// Staticlint проверяет пакеты stonemcp анализаторами go vet, staticcheck,
// nilerr и собственным osexitcheck.
//
// # Запуск
//
//	make lint
//	go run ./cmd/staticlint ./...
//
// Код выхода 0 означает отсутствие находок, код 3 означает найденные
// нарушения. Команда staticlint help перечисляет анализаторы, а staticlint
// help с именем анализатора описывает его и его флаги.
//
// # Проверки staticcheck
//
// Файл config.json встраивается в бинарник при сборке и выбирает проверки
// staticcheck. Поле prefixes включает проверки по префиксу имени, required
// перечисляет обязательные префиксы, exclude выключает отдельные проверки.
// Ошибка в файле останавливает staticlint до анализа.
//
//	SA   ошибки и подозрительные конструкции, класс обязателен целиком
//	S1   упрощение кода
//	ST1  оформление и именование
//	QF1  быстрые исправления, кроме QF1008
//
// # Состав
//
//	go vet       набор golang.org/x/tools/go/analysis/suite/vet
//	nilerr       возврат nil при ненулевой ошибке и ошибки при нулевой
//	osexitcheck  прямой вызов os.Exit в функции main пакета main
